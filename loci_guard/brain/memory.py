"""Persistent project memory that survives across AI sessions."""

from __future__ import annotations

import hashlib
import time
from pathlib import Path
from typing import Any

from loci_guard.brain.store import JsonStore
from loci_guard.brain.text import lost_details


MAX_VERSIONS = 20
MEMORY_DIR = ".loci"
MEMORY_FILE = "memory.json"
RULES_FILE = "rules.json"


class ProjectMemory:
    """Stores and retrieves project knowledge across sessions.

    Persists to .loci/ in the project root so it travels with the repo.
    """

    def __init__(self, project_root: str | Path):
        self.root = Path(project_root).resolve()
        self.memory_dir = self.root / MEMORY_DIR
        self._memory_path = self.memory_dir / MEMORY_FILE
        self._store = JsonStore(self._memory_path, {
            "version": 1, "created_at": time.time(), "updated_at": time.time(),
            "scan": {}, "decisions": [], "constraints": [],
        })
        self._data = self._store.data
        self.last_lost: list[str] = []

    def save(self) -> None:
        self._data["updated_at"] = time.time()
        self._store.save()

    def store_scan(self, scan_result: dict) -> None:
        self._data["scan"] = scan_result
        self._data["scan"]["scanned_at"] = time.time()
        self.save()

    def add_decision(self, description: str, reason: str, files: list[str] | None = None) -> None:
        """Record an architectural or convention decision."""
        entry = {
            "id": hashlib.sha256(f"{description}{time.time()}".encode()).hexdigest()[:12],
            "description": description,
            "reason": reason,
            "files": files or [],
            "created_at": time.time(),
        }
        self._data["decisions"].append(entry)
        self.save()

    def add_constraint(
        self,
        name: str,
        rule: str,
        severity: str = "warning",
        auto_learned: bool = False,
    ) -> None:
        """Add or update a project constraint, keyed by name."""
        self.last_lost = []
        constraints = self._data.setdefault("constraints", [])
        for existing in constraints:
            if existing["name"] == name:
                # Never let a re-scan overwrite a constraint the user wrote by hand.
                if auto_learned and not existing.get("auto_learned", False):
                    return
                # Rules a person wrote keep their history; auto-learned ones are regenerated by every scan.
                if not auto_learned and existing["rule"] != rule:
                    versions = existing.setdefault("versions", [])
                    versions.append({"rule": existing["rule"], "severity": existing.get("severity"), "until": time.time()})
                    del versions[:-MAX_VERSIONS]
                    self.last_lost = lost_details(existing["rule"], rule)
                existing.update(rule=rule, severity=severity, auto_learned=auto_learned)
                existing["updated_at"] = time.time()
                self.save()
                return
        constraints.append({
            "id": hashlib.sha256(name.encode()).hexdigest()[:12],
            "name": name,
            "rule": rule,
            "severity": severity,
            "auto_learned": auto_learned,
            "created_at": time.time(),
            "active": True,
        })
        self.save()

    def remove_constraint(self, name: str) -> bool:
        before = len(self._data.get("constraints", []))
        self._data["constraints"] = [
            c for c in self._data.get("constraints", []) if c["name"] != name
        ]
        removed = len(self._data["constraints"]) < before
        if removed:
            self.save()
        return removed

    def get_constraints(self, active_only: bool = True) -> list[dict]:
        constraints = self._data.get("constraints", [])
        if active_only:
            return [c for c in constraints if c.get("active", True)]
        return constraints

    @property
    def data(self) -> dict[str, Any]:
        return self._data
